import { build } from 'esbuild';
import { cp, mkdir, rm } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { ensureNative } from './scripts/fetch-native.mjs';
const here = path.dirname(fileURLToPath(import.meta.url));
await rm(path.join(here, 'dist'), { recursive: true, force: true });
await mkdir(path.join(here, 'dist'), { recursive: true });
for (const name of ['main', 'preload']) await build({ absWorkingDir: here, entryPoints: [name + '.ts'], outfile: 'dist/' + name + '.cjs', bundle: true, platform: 'node', format: 'cjs', target: 'node22', external: ['electron'] });
await build({ absWorkingDir: here, entryPoints: ['ui/renderer.ts'], outfile: 'dist/renderer.js', bundle: true, platform: 'browser', format: 'iife', target: 'chrome140' });
for (const file of ['index.html', 'style.css']) await cp(path.join(here, 'ui', file), path.join(here, 'dist', file));
await cp(path.join(here, 'QUICKSTART-WINDOWS.txt'), path.join(here, 'dist', 'QUICKSTART-WINDOWS.txt'));
const extensionOut = path.join(here, 'dist', 'browser-extension');
await mkdir(extensionOut, { recursive: true });
await build({ absWorkingDir: here, entryPoints: ['extension/content.ts'], outfile: 'dist/browser-extension/content.js', bundle: true, platform: 'browser', format: 'iife', target: 'chrome120' });
for (const file of ['manifest.json', 'background.js', 'popup.html', 'popup.css', 'popup.js']) await cp(path.join(here, 'extension', file), path.join(extensionOut, file));
const stockfishOut = path.join(here, 'dist', 'stockfish');
await mkdir(stockfishOut, { recursive: true });
for (const file of ['stockfish-19-lite-single.js', 'stockfish-19-lite-single.wasm']) await cp(path.resolve(here, '../node_modules/stockfish/bin', file), path.join(stockfishOut, file));
await cp(path.resolve(here, '../node_modules/stockfish/Copying.txt'), path.join(stockfishOut, 'Copying.txt'));
await cp(path.join(here, 'THIRD-PARTY.txt'), path.join(stockfishOut, 'SOURCE.txt'));
const nativeSource = await ensureNative();
await cp(nativeSource, path.join(here, 'dist', 'stockfish-native'), { recursive: true });
